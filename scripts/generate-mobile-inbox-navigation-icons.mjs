// Additional native destinations use the same maintained Iconify packs as the
// existing theme icon generator. Run from the repository dependency environment.
import lucide from "@iconify-json/lucide/icons.json";
import heroicons from "@iconify-json/heroicons/icons.json";
import phosphor from "@iconify-json/ph/icons.json";
import tabler from "@iconify-json/tabler/icons.json";
import { getIconData } from "@iconify/utils/lib/icon-set/get-icon";
import { iconToSVG } from "@iconify/utils/lib/svg/build";
import sharp from "sharp";
import { format } from "oxfmt";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve, dirname } from "node:path";
const mobile = resolve(dirname(fileURLToPath(import.meta.url)), "../apps/mobile");
const packs = {
  lucide: [lucide, { inbox: "messages-square", media: "images", more: "ellipsis" }],
  "heroicons-outline": [
    heroicons,
    { inbox: "chat-bubble-left-right", media: "photo", more: "ellipsis-horizontal" },
  ],
  "heroicons-solid": [
    heroicons,
    {
      inbox: "chat-bubble-left-right-solid",
      media: "photo-solid",
      more: "ellipsis-horizontal-solid",
    },
  ],
  phosphor: [phosphor, { inbox: "chats", media: "images", more: "dots-three" }],
  tabler: [tabler, { inbox: "messages", media: "photo", more: "dots" }],
};
const check = process.argv.includes("--check");
const source = [
  "// Generated by scripts/generate-mobile-inbox-navigation-icons.mjs.",
  'import type { ImageSourcePropType } from "react-native";',
  'import type { NativeIconPackId } from "./contract";',
  'export type InboxNavigationRole = "inbox" | "media" | "more";',
  "export const INBOX_NAVIGATION_ICONS = {",
];
async function output(path, content) {
  if (check) {
    if (!Buffer.from(await readFile(path)).equals(Buffer.from(content)))
      throw new Error(`Stale native icon: ${path}`);
  } else await writeFile(path, content);
}
for (const [id, [collection, roles]] of Object.entries(packs)) {
  source.push(`  ${JSON.stringify(id)}: {`);
  for (const [role, glyph] of Object.entries(roles)) {
    const data = getIconData(collection, glyph);
    if (!data) throw new Error(`Missing glyph ${id}:${glyph}`);
    const icon = iconToSVG(data, {});
    const xml = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${icon.attributes.viewBox}" color="white">${icon.body}</svg>`;
    const directory = resolve(mobile, "assets/theme-icons", id);
    await mkdir(directory, { recursive: true });
    for (const scale of [1, 2, 3]) {
      const png = await sharp(Buffer.from(xml))
        .resize(24 * scale, 24 * scale)
        .png()
        .toBuffer();
      await output(resolve(directory, `${role}${scale === 1 ? "" : `@${scale}x`}.png`), png);
    }
    source.push(`    ${role}: require("../../assets/theme-icons/${id}/${role}.png"),`);
  }
  source.push("  },");
}
source.push(
  "} satisfies Readonly<Record<NativeIconPackId, Readonly<Record<InboxNavigationRole, ImageSourcePropType>>>>;",
  "",
);
const destination = resolve(mobile, "src/theme/inbox-navigation-icons.generated.ts");
const formatted = await format(destination, source.join("\n"), { printWidth: 100 });
if (formatted.errors.length) throw new Error("Could not format native navigation icons");
await output(destination, formatted.code);
